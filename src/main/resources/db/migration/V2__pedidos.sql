CREATE TABLE pedido (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id         BIGINT         NOT NULL REFERENCES cliente (id),
    situacao           TEXT           NOT NULL,
    entrega_apelido    VARCHAR(60),
    entrega_cep        CHAR(8)        NOT NULL,
    entrega_logradouro VARCHAR(255)   NOT NULL,
    entrega_numero     VARCHAR(20)    NOT NULL,
    entrega_complemento VARCHAR(100),
    entrega_bairro     VARCHAR(100)   NOT NULL,
    entrega_cidade     VARCHAR(100)   NOT NULL,
    entrega_uf         CHAR(2)        NOT NULL,
    subtotal           NUMERIC(12, 2) NOT NULL,
    total_descontos    NUMERIC(12, 2) NOT NULL,
    frete              NUMERIC(12, 2) NOT NULL,
    total              NUMERIC(12, 2) NOT NULL,
    criado_em          TIMESTAMPTZ    NOT NULL,
    versao             BIGINT         NOT NULL DEFAULT 0,
    CONSTRAINT ck_pedido_situacao
        CHECK (situacao IN ('CRIADO', 'AGUARDANDO_PAGAMENTO', 'PAGO', 'PAGAMENTO_RECUSADO',
                            'EM_PREPARACAO', 'ENVIADO', 'ENTREGUE', 'CANCELADO'))
);

CREATE INDEX ix_pedido_cliente_criado_em ON pedido (cliente_id, criado_em DESC);
CREATE INDEX ix_pedido_situacao ON pedido (situacao);

CREATE TABLE pedido_item (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id          BIGINT         NOT NULL REFERENCES pedido (id),
    sku                VARCHAR(100)   NOT NULL,
    nome_produto       VARCHAR(255)   NOT NULL,
    descricao_variacao VARCHAR(255),
    quantidade         INTEGER        NOT NULL,
    preco_unitario     NUMERIC(12, 2) NOT NULL,
    total_item         NUMERIC(12, 2) NOT NULL,
    CONSTRAINT ck_pedido_item_quantidade CHECK (quantidade > 0)
);

CREATE INDEX ix_pedido_item_pedido ON pedido_item (pedido_id);

CREATE TABLE pedido_desconto (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id BIGINT         NOT NULL REFERENCES pedido (id),
    descricao VARCHAR(255)   NOT NULL,
    origem    TEXT           NOT NULL,
    alvo      TEXT           NOT NULL,
    valor     NUMERIC(12, 2) NOT NULL,
    CONSTRAINT ck_pedido_desconto_origem CHECK (origem IN ('PROMOCAO', 'CUPOM')),
    CONSTRAINT ck_pedido_desconto_alvo CHECK (alvo IN ('ITENS', 'FRETE'))
);

CREATE INDEX ix_pedido_desconto_pedido ON pedido_desconto (pedido_id);

-- "de" e nulo na entrada de criacao do pedido. O responsavel e de tres tipos; o usuario so existe para CLIENTE e ADMINISTRATIVO.
CREATE TABLE pedido_historico (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id              BIGINT      NOT NULL REFERENCES pedido (id),
    de                     TEXT,
    para                   TEXT        NOT NULL,
    ocorrido_em            TIMESTAMPTZ NOT NULL,
    responsavel_tipo       TEXT        NOT NULL,
    responsavel_usuario_id BIGINT,
    motivo                 TEXT,
    CONSTRAINT ck_pedido_historico_de
        CHECK (de IS NULL OR de IN ('CRIADO', 'AGUARDANDO_PAGAMENTO', 'PAGO', 'PAGAMENTO_RECUSADO',
                                    'EM_PREPARACAO', 'ENVIADO', 'ENTREGUE', 'CANCELADO')),
    CONSTRAINT ck_pedido_historico_para
        CHECK (para IN ('CRIADO', 'AGUARDANDO_PAGAMENTO', 'PAGO', 'PAGAMENTO_RECUSADO',
                        'EM_PREPARACAO', 'ENVIADO', 'ENTREGUE', 'CANCELADO')),
    CONSTRAINT ck_pedido_historico_responsavel_tipo
        CHECK (responsavel_tipo IN ('CLIENTE', 'ADMINISTRATIVO', 'SISTEMA'))
);

CREATE INDEX ix_pedido_historico_pedido ON pedido_historico (pedido_id);
