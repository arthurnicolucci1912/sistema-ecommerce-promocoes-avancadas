CREATE TABLE promocao_config (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 versao BIGINT NOT NULL DEFAULT 0, nome VARCHAR(255) NOT NULL, tipo VARCHAR(100) NOT NULL,
 ativo BOOLEAN NOT NULL DEFAULT TRUE, inicio TIMESTAMPTZ NOT NULL, fim TIMESTAMPTZ NOT NULL,
 criado_em TIMESTAMPTZ NOT NULL, prioridade INTEGER NOT NULL,
 modo VARCHAR(30) NOT NULL CHECK (modo IN ('ACUMULAVEL','NAO_ACUMULAVEL','EXCLUSIVA')),
 parametros JSONB NOT NULL, condicao JSONB,
 CHECK (inicio < fim)
);
CREATE INDEX ix_promocao_vigencia ON promocao_config(ativo,inicio,fim);
CREATE TABLE cupom (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 versao BIGINT NOT NULL DEFAULT 0, nome VARCHAR(255) NOT NULL, tipo VARCHAR(100) NOT NULL,
 ativo BOOLEAN NOT NULL DEFAULT TRUE, inicio TIMESTAMPTZ NOT NULL, fim TIMESTAMPTZ NOT NULL,
 criado_em TIMESTAMPTZ NOT NULL, codigo VARCHAR(40) NOT NULL,
 acumulavel BOOLEAN NOT NULL, limite_total INTEGER NOT NULL CHECK(limite_total>0),
 limite_cliente INTEGER CHECK(limite_cliente>0), parametros JSONB NOT NULL, condicao JSONB,
 CONSTRAINT uk_cupom_codigo UNIQUE(codigo), CHECK(codigo ~ '^[A-Z0-9_-]{3,40}$'), CHECK(inicio<fim)
);
CREATE TABLE saldo_cupom (
 cupom_id BIGINT PRIMARY KEY REFERENCES cupom(id), usos_ativos INTEGER NOT NULL DEFAULT 0 CHECK(usos_ativos>=0)
);
CREATE TABLE uso_cupom (
 pedido_id BIGINT PRIMARY KEY, cliente_id BIGINT NOT NULL, cupom_id BIGINT NOT NULL REFERENCES cupom(id),
 situacao VARCHAR(20) NOT NULL CHECK(situacao IN ('CONSUMIDO','DEVOLVIDO')),
 consumido_em TIMESTAMPTZ NOT NULL, devolvido_em TIMESTAMPTZ
);
CREATE INDEX ix_uso_cupom_cliente ON uso_cupom(cupom_id,cliente_id,situacao);
ALTER TABLE carrinho ADD COLUMN cupom_codigo VARCHAR(40);
ALTER TABLE pedido_desconto ADD COLUMN referencia_id BIGINT;
ALTER TABLE pedido_desconto ADD COLUMN codigo VARCHAR(40);
