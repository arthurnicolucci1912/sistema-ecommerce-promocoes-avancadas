CREATE TABLE auditoria_operacao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL CHECK (usuario_id > 0),
    ocorrido_em TIMESTAMPTZ NOT NULL,
    operacao VARCHAR(100) NOT NULL,
    recurso_tipo VARCHAR(100) NOT NULL,
    recurso_id BIGINT NOT NULL CHECK (recurso_id > 0),
    detalhes JSONB NOT NULL CHECK (jsonb_typeof(detalhes) = 'object')
);
CREATE INDEX ix_auditoria_momento ON auditoria_operacao (ocorrido_em DESC, id DESC);
CREATE INDEX ix_auditoria_usuario_momento ON auditoria_operacao (usuario_id, ocorrido_em DESC, id DESC);
CREATE INDEX ix_auditoria_operacao_momento ON auditoria_operacao (operacao, ocorrido_em DESC, id DESC);
