CREATE TABLE usuario (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(255) NOT NULL,
    senha_hash    VARCHAR(255) NOT NULL,
    ativo         BOOLEAN      NOT NULL DEFAULT TRUE,
    criado_em     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    atualizado_em TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uk_usuario_email UNIQUE (email)
);

CREATE TABLE usuario_perfil (
    usuario_id BIGINT NOT NULL REFERENCES usuario (id),
    perfil     TEXT   NOT NULL,
    PRIMARY KEY (usuario_id, perfil),
    CONSTRAINT ck_usuario_perfil_perfil
        CHECK (perfil IN ('CLIENTE', 'ADMIN', 'OPERADOR_COMERCIAL', 'ESTOQUE', 'PROMOCOES'))
);

CREATE TABLE cliente (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT       NOT NULL REFERENCES usuario (id),
    nome       VARCHAR(255) NOT NULL,
    cpf        CHAR(11)     NOT NULL,
    telefone   VARCHAR(20),
    CONSTRAINT uk_cliente_usuario UNIQUE (usuario_id),
    CONSTRAINT uk_cliente_cpf UNIQUE (cpf)
);

CREATE TABLE endereco (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id  BIGINT       NOT NULL REFERENCES cliente (id),
    apelido     VARCHAR(60),
    cep         CHAR(8)      NOT NULL,
    logradouro  VARCHAR(255) NOT NULL,
    numero      VARCHAR(20)  NOT NULL,
    complemento VARCHAR(100),
    bairro      VARCHAR(100) NOT NULL,
    cidade      VARCHAR(100) NOT NULL,
    uf          CHAR(2)      NOT NULL,
    principal   BOOLEAN      NOT NULL DEFAULT FALSE,
    ativo       BOOLEAN      NOT NULL DEFAULT TRUE,
    criado_em   TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE INDEX ix_endereco_cliente ON endereco (cliente_id);

-- No maximo um endereco principal ativo por cliente, garantido pelo banco.
CREATE UNIQUE INDEX ux_endereco_principal_ativo ON endereco (cliente_id) WHERE principal AND ativo;
