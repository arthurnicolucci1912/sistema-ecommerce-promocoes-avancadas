CREATE TABLE categoria (
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome   VARCHAR(100) NOT NULL,
    pai_id BIGINT REFERENCES categoria (id)
);

-- Nome unico por pai, sem diferenciar maiusculas; as categorias raiz (pai nulo) compartilham o "pai 0".
CREATE UNIQUE INDEX ux_categoria_pai_nome ON categoria (COALESCE(pai_id, 0), LOWER(nome));

CREATE TABLE produto (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome         VARCHAR(255) NOT NULL,
    descricao    TEXT,
    marca        VARCHAR(100),
    categoria_id BIGINT       NOT NULL REFERENCES categoria (id),
    ativo        BOOLEAN      NOT NULL DEFAULT TRUE,
    criado_em    TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE INDEX ix_produto_categoria ON produto (categoria_id);

-- Raiz da heranca JOINED do item vendavel (Composite): variacao_produto e combo compartilham o id desta tabela.
CREATE TABLE item_vendavel (
    id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku   VARCHAR(60)    NOT NULL,
    nome  VARCHAR(255)   NOT NULL,
    preco NUMERIC(12, 2) NOT NULL,
    ativo BOOLEAN        NOT NULL DEFAULT TRUE,
    tipo  VARCHAR(20)    NOT NULL,
    CONSTRAINT uk_item_vendavel_sku UNIQUE (sku),
    CONSTRAINT ck_item_vendavel_preco CHECK (preco > 0),
    CONSTRAINT ck_item_vendavel_tipo CHECK (tipo IN ('VARIACAO', 'COMBO'))
);

CREATE TABLE variacao_produto (
    id         BIGINT PRIMARY KEY REFERENCES item_vendavel (id),
    produto_id BIGINT NOT NULL REFERENCES produto (id)
);

CREATE INDEX ix_variacao_produto_produto ON variacao_produto (produto_id);

CREATE TABLE variacao_atributo (
    variacao_id BIGINT       NOT NULL REFERENCES variacao_produto (id),
    nome        VARCHAR(100) NOT NULL,
    valor       VARCHAR(255) NOT NULL,
    PRIMARY KEY (variacao_id, nome)
);

CREATE TABLE combo (
    id BIGINT PRIMARY KEY REFERENCES item_vendavel (id)
);

CREATE TABLE combo_item (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    combo_id   BIGINT  NOT NULL REFERENCES combo (id),
    item_id    BIGINT  NOT NULL REFERENCES item_vendavel (id),
    quantidade INTEGER NOT NULL,
    CONSTRAINT uk_combo_item UNIQUE (combo_id, item_id),
    CONSTRAINT ck_combo_item_quantidade CHECK (quantidade > 0),
    CONSTRAINT ck_combo_item_nao_contem_a_si_mesmo CHECK (combo_id <> item_id)
);

-- Sem FK para variacao_produto: o modulo estoque nao depende do esquema do catalogo. variacao_id e so a referencia.
CREATE TABLE saldo_estoque (
    variacao_id   BIGINT      PRIMARY KEY,
    disponivel    INTEGER     NOT NULL DEFAULT 0,
    reservado     INTEGER     NOT NULL DEFAULT 0,
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_saldo_estoque_disponivel CHECK (disponivel >= 0),
    CONSTRAINT ck_saldo_estoque_reservado CHECK (reservado >= 0)
);

-- Sem FK para pedido nem para variacao_produto: o estoque nao depende do esquema de outros modulos.
-- pedido_id e variacao_id sao so referencias.
CREATE TABLE reserva_estoque (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id     BIGINT      NOT NULL,
    variacao_id   BIGINT      NOT NULL,
    quantidade    INTEGER     NOT NULL,
    situacao      VARCHAR(20) NOT NULL,
    criado_em     TIMESTAMPTZ NOT NULL DEFAULT now(),
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uk_reserva_estoque_pedido_variacao UNIQUE (pedido_id, variacao_id),
    CONSTRAINT ck_reserva_estoque_quantidade CHECK (quantidade > 0),
    CONSTRAINT ck_reserva_estoque_situacao CHECK (situacao IN ('ATIVA', 'LIBERADA', 'BAIXADA', 'REPOSTA'))
);

CREATE INDEX ix_reserva_estoque_pedido ON reserva_estoque (pedido_id);
