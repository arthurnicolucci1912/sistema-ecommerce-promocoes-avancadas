CREATE TABLE carrinho (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id BIGINT NOT NULL REFERENCES cliente(id),
    versao BIGINT NOT NULL DEFAULT 0,
    revisao BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uk_carrinho_cliente UNIQUE (cliente_id)
);

CREATE TABLE item_carrinho (
    carrinho_id BIGINT NOT NULL REFERENCES carrinho(id),
    sku VARCHAR(100) NOT NULL,
    item_vendavel_id BIGINT NOT NULL,
    nome VARCHAR(255) NOT NULL,
    preco_referencia NUMERIC(19, 2) NOT NULL,
    quantidade INTEGER NOT NULL,
    PRIMARY KEY (carrinho_id, sku),
    CONSTRAINT ck_item_carrinho_quantidade CHECK (quantidade > 0),
    CONSTRAINT ck_item_carrinho_preco CHECK (preco_referencia > 0)
);

-- Referencias comerciais sem FK para permitir exibir/remover linhas fora do catalogo.
